const drag_model_def_t* get_drag_model_def(drag_model_type_t type) {
    for (int i = 0; i < sizeof(drag_models) / sizeof(drag_models[0]); i++) {
        if (drag_models[i].type == type) {
            return &drag_models[i];
        }
    }
    return NULL;
}

float get_drag_coefficient_for_model(drag_model_type_t model_type, float mach) {
    const drag_model_def_t* model = get_drag_model_def(model_type);
    if (!model) {
        return 0.0f;
    }
    
    // Find bracketing points in the table
    const drag_table_entry_t* table = model->table;
    uint16_t size = model->table_size;
    
    // Below table range
    if (mach <= table[0].mach) {
        return table[0].cd;
    }
    
    // Above table range
    if (mach >= table[size - 1].mach) {
        return table[size - 1].cd;
    }
    
    // Interpolate within table
    for (int i = 0; i < size - 1; i++) {
        if (mach >= table[i].mach && mach <= table[i + 1].mach) {
            return ballistic_interpolate_linear(mach,
                                              table[i].mach, table[i].cd,
                                              table[i + 1].mach, table[i + 1].cd);
        }
    }
    
    // Fallback
    return table[0].cd;
}

