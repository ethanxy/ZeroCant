static int get_model_index(drag_model_type_t model) {
    switch (model) {
        case DRAG_MODEL_G1: return 0;
        case DRAG_MODEL_G2: return 1;
        case DRAG_MODEL_G5: return 2;
        case DRAG_MODEL_G6: return 3;
        case DRAG_MODEL_G7: return 4;
        case DRAG_MODEL_G8: return 5;
        case DRAG_MODEL_GI: return 6;
        default: return 0;
    }
}

float convert_bc_between_models(float bc_value, 
                               drag_model_type_t from_model, 
                               drag_model_type_t to_model,
                               float mach) {
    if (from_model == to_model) {
        return bc_value;
    }
    
    int from_idx = get_model_index(from_model);
    int to_idx = get_model_index(to_model);
    
    float conversion_ratio = bc_conversion_ratios[from_idx][to_idx];
    
    // Apply mach-dependent correction (simplified)
    if (mach > 1.2f) {
        conversion_ratio *= 0.95f;  // Supersonic correction
    } else if (mach < 0.8f) {
        conversion_ratio *= 1.05f;  // Subsonic correction
    }
    
    return bc_value * conversion_ratio;
}

const drag_model_def_t** get_all_drag_models(uint8_t* count) {
    static const drag_model_def_t* model_list[7];
    
    for (int i = 0; i < 7; i++) {
        model_list[i] = &drag_models[i];
    }
    
    if (count) {
        *count = 7;
    }
    
    return model_list;
}
